"""
evaluation/report.py

Renders the experiment results into a self-contained Markdown report that
doubles as the research write-up for the Shifa RAG evaluation suite.
"""

from __future__ import annotations

import json
import os
from typing import Dict, List

_METRIC_LABELS = {
    "recall@5": "Recall@5",
    "recall@10": "Recall@10",
    "precision@5": "Precision@5",
    "precision@10": "Precision@10",
    "mrr": "MRR@10",
    "ndcg@10": "nDCG@10",
}

_METRIC_ORDER = ["recall@5", "recall@10", "precision@5", "precision@10", "mrr", "ndcg@10"]


def _fmt(value) -> str:
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def _metric_table(rows: List[Dict[str, object]], name_key: str = "condition") -> str:
    header = ["Metric"] + [_fmt(r[name_key]) for r in rows]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for metric in _METRIC_ORDER:
        line = f"| {_METRIC_LABELS.get(metric, metric)} |"
        for row in rows:
            agg = row["aggregate"]
            line += f" {_fmt(agg.get(metric, 0.0))} |"
        lines.append(line)
    return "\n".join(lines)


def _best_per_row(rows: List[Dict[str, object]]) -> Dict[str, str]:
    """For each metric, which condition is best (highest value)."""
    best: Dict[str, str] = {}
    for metric in _METRIC_ORDER:
        values = [(row["name"], row["aggregate"].get(metric, 0.0)) for row in rows]
        if values:
            name, _ = max(values, key=lambda v: v[1])
            best[metric] = name
    return best


def _load_json(path: str) -> Dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def build_report(
    results_dir: str,
    artifacts: Dict[str, str],
    summary: Dict,
) -> str:
    """Assemble the full markdown report."""
    lines: List[str] = []
    add = lines.append

    add("# Shifa RAG — Evaluation Report")
    add("")
    add(
        "_Generated by `evaluation.run_evaluation`. This is a research benchmark for "
        "retrieval and generation experimentation on educational medical summaries — "
        "it is **not** a clinical validation study, and results must not be presented "
        "as clinical evidence._"
    )
    add("")

    # ---------------------------------------------------------- overview
    add("## 1. Benchmark overview")
    add("")
    cstats = summary.get("corpus", {})
    qstats = summary.get("dataset", {})
    add(
        f"- **Corpus**: {cstats.get('documents', 0)} original educational medical "
        f"documents (~{cstats.get('words', 0):,} words, {cstats.get('topics', 0)} topic areas)."
    )
    add(
        f"- **Questions**: {qstats.get('questions', 0)} QA pairs "
        f"({qstats.get('single_doc', 0)} single-document, {qstats.get('multi_doc', 0)} "
        "multi-document), each annotated with an expected answer and the relevant document(s)."
    )
    add(
        "- **Relevance level**: document-level. A retrieved chunk is a hit if its "
        "originating document is in the question's relevant set."
    )
    add(
        "- **Metrics**: Recall@5, Recall@10, Precision@5, Precision@10, MRR@10, nDCG@10 "
        "(retrieval); faithfulness, hallucination rate, answer relevance, context "
        "relevance (generation)."
    )
    add("")
    add("Run configuration: " + ", ".join(f"`{k}={v}`" for k, v in summary.get("config", {}).items()))
    add("")

    # ---------------------------------------------------------- exp 1
    exp1_path = artifacts.get("retrieval_methods")
    if exp1_path and os.path.exists(exp1_path):
        exp1 = _load_json(exp1_path)
        add("## 2. Experiment 1 — Retrieval method comparison")
        add("")
        add("**Question**: which retrieval strategy — BM25 (sparse), dense, or hybrid "
            "(RRF fusion) — works best for domain-specific medical QA?")
        add("")
        add("**Controls**: chunk size 512 tokens; embedding model `"
            + exp1["config"]["embedding_model"].split("/")[-1] + "`; "
            f"{exp1['config']['queries']} queries.")
        add("")
        rows = [
            {"name": method, "aggregate": exp1["results"][method]["aggregate"]}
            for method in exp1["results"]
        ]
        add(_metric_table(rows, name_key="name"))
        add("")
        best = _best_per_row(rows)
        add("**Best per metric**: " + ", ".join(
            f"{_METRIC_LABELS[m]} → {b}" for m, b in best.items()
        ))
        add("")
        # ---- subset breakdown
        subsets = exp1.get("subsets", {})
        if subsets:
            add("### Breakdown by question subset")
            add("")
            for method, sub_results in subsets.items():
                add(f"**`{method}`**")
                add("")
                for sname, agg in sub_results.items():
                    add(
                        f"- `{sname}` (n={agg.get('queries', '?')}): "
                        f"R@5={agg['recall@5']:.4f}, R@10={agg['recall@10']:.4f}, "
                        f"MRR={agg['mrr']:.4f}"
                    )
                add("")
            add("The `hard` and `multi_doc` subsets are where retrieval strategies "
                "separate; near-ceiling scores on the full set mean most questions are "
                "answerable by any reasonable retriever.")
            add("")

    # ---------------------------------------------------------- exp 2
    exp2_path = artifacts.get("embedding_models")
    if exp2_path and os.path.exists(exp2_path):
        exp2 = _load_json(exp2_path)
        add("## 3. Experiment 2 — Embedding model comparison")
        add("")
        add("**Question**: does the embedding model change retrieval quality when "
            "everything else is fixed?")
        add("")
        add("**Controls**: chunk size 512 tokens; "
            f"{exp2['config']['queries']} queries; dense and hybrid retrieval.")
        add("")
        for method in exp2["config"]["methods"]:
            add(f"### Dense/hybrid — `{method}` retrieval")
            add("")
            rows = []
            for model, res in exp2["results"].items():
                short = model.split("/")[-1]
                rows.append({"name": short, "aggregate": res[method]["aggregate"]})
            add(_metric_table(rows, name_key="name"))
            add("")
            best = _best_per_row(rows)
            add("**Best per metric**: " + ", ".join(
                f"{_METRIC_LABELS[m]} → {b}" for m, b in best.items()
            ))
            add("")

    # ---------------------------------------------------------- exp 3
    exp3_path = artifacts.get("chunk_size")
    if exp3_path and os.path.exists(exp3_path):
        exp3 = _load_json(exp3_path)
        add("## 4. Experiment 3 — Chunk-size study")
        add("")
        add("**Research question**: how does chunk size affect retrieval quality in "
            "domain-specific medical QA?")
        add("")
        add("**Controls**: embedding model `" + exp3["config"]["embedding_model"].split("/")[-1]
            + f"`; {exp3['config']['queries']} queries; sizes in tokens "
            "(token-count based, no overlap).")
        add("")
        for method in exp3["config"]["methods"]:
            add(f"### `{method}` retrieval")
            add("")
            rows = []
            for size, res in exp3["results"].items():
                rows.append({"name": f"{size} tok", "aggregate": res[method]["aggregate"]})
            add(_metric_table(rows, name_key="name"))
            add("")
            best = _best_per_row(rows)
            add("**Best per metric**: " + ", ".join(
                f"{_METRIC_LABELS[m]} → {b}" for m, b in best.items()
            ))
            add("")

    # ---------------------------------------------------------- exp 4
    exp4_path = artifacts.get("generation_stage")
    if exp4_path and os.path.exists(exp4_path):
        exp4 = _load_json(exp4_path)
        add("## 5. Experiment 4 — Generation-stage evaluation")
        add("")
        add("**Question**: once retrieval is fixed, how faithful and relevant are the "
            "generated answers, and how much hallucination occurs?")
        add("")
        add("**Controls**: retrieval method `" + exp4["config"]["retrieval_method"]
            + "`; chunk size " + str(exp4["config"]["chunk_size_tokens"]) + " tokens; model `"
            + exp4["config"]["embedding_model"].split("/")[-1] + "`; "
            f"{exp4['config']['queries']} queries.")
        add("")
        judge_state = "available (Gemini)" if exp4["config"].get("llm_judge") else "unavailable (no API key) — heuristic scorer used"
        add("Generators: " + ", ".join(f"`{g}`" for g in exp4["config"]["generators"])
            + f" — LLM-as-judge: {judge_state}.")
        add("")
        for gen, res in exp4["results"].items():
            agg = res["aggregate"]
            add(f"### Generator: `{gen}` (judge: `{agg['judge']}`)")
            add("")
            add("| Metric | Value |")
            add("|---|---|")
            for key in ["faithfulness", "hallucination_rate", "answer_relevance", "context_relevance"]:
                add(f"| {key.replace('_', ' ').title()} | {_fmt(agg[key])} |")
            add("")

    # ---------------------------------------------------------- findings
    add("## 6. Findings & how to read them")
    add("")
    add("- Retrieval metrics answer **which retriever/config finds the right documents**; "
        "generation metrics answer **whether the answer is grounded in what was retrieved**.")
    add("- A high Recall@10 with low Recall@5 means the right document is in the pool but "
        "not ranked near the top — a reranking or fusion opportunity.")
    add("- Hallucination rate is the fraction of answer claims unsupported by the "
        "retrieved context. Compare it across generators with retrieval held fixed.")
    add("- This benchmark is a **controlled research harness**, not a clinical "
        "evaluation. It should be described as domain-specific QA/retrieval "
        "experimentation, not medical diagnosis validation.")
    add("")
    add("## 7. Reproducibility")
    add("")
    add("```bash")
    add("cd backend/rag-service2")
    add("python -m evaluation.run_evaluation --experiments 1,2,3,4")
    add("```")
    add("")
    add("Raw per-query results are in the JSON files next to this report.")

    return "\n".join(lines)


def write_report(
    results_dir: str,
    artifacts: Dict[str, str],
    summary: Dict,
    report_path: str = "evaluation/results/report.md",
) -> str:
    markdown = build_report(results_dir, artifacts, summary)
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(markdown)
    return report_path
